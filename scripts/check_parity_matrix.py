#!/usr/bin/env python3
"""Validate the executable parity matrix and regenerate its report.

The matrix is the single source of truth for migration completeness. This
checker is deliberately conservative: it fails on unknown categories or
offline classifications, duplicate IDs, empty/TBD cells, rows without tests,
and any reference behavior that no row mentions.

The reference tree (`spliit/`) is not committed. When it is present (local
checkouts), it is the source of truth; otherwise the committed inventory in
`docs/reference-manifest.txt` is used, so CI enforces the same coverage without
the reference source.

Usage:
    python scripts/check_parity_matrix.py
    python scripts/check_parity_matrix.py --write-reference-manifest

Exit codes:
    0  matrix is complete and consistent (report regenerated)
    1  validation failed
    2  PyYAML is not installed
"""

from __future__ import annotations

import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MATRIX = ROOT / "docs" / "parity-matrix.yml"
REPORT = ROOT / "docs" / "parity-report.md"
MANIFEST = ROOT / "docs" / "reference-manifest.txt"
REFERENCE = ROOT / "spliit"

REQUIRED_FIELDS = ("id", "category", "reference", "api", "ui", "stage", "tests", "offline")
VALID_CATEGORIES = {"standard", "custom"}
VALID_OFFLINE = {"read-write", "read-only", "queued", "online-only"}
TBD_MARKERS = {"", "tbd", "todo", "?", "unknown"}

KINDS = ("pages", "procedures", "jest", "e2e")
KIND_LABELS = {
    "pages": "page",
    "procedures": "tRPC procedure file",
    "jest": "Jest suite",
    "e2e": "Playwright spec",
}

# Files that contain procedures but are not named *.procedure.ts.
EXTRA_ROUTER_FILES = (
    REFERENCE / "src/trpc/routers/admin/index.ts",
    REFERENCE / "src/trpc/routers/auth/index.ts",
)


def fail(message: str) -> None:
    print(f"FAIL: {message}", file=sys.stderr)


def load_matrix():
    try:
        import yaml
    except ImportError:  # pragma: no cover - environment guard
        print(
            "PyYAML is required. Install it in the backend virtualenv:\n"
            "  backend/.venv/bin/pip install -r backend/requirements-dev.txt",
            file=sys.stderr,
        )
        raise SystemExit(2)

    if not MATRIX.exists():
        fail(f"missing matrix: {MATRIX.relative_to(ROOT)}")
        raise SystemExit(1)

    data = yaml.safe_load(MATRIX.read_text())
    if not isinstance(data, list) or not data:
        fail("matrix must be a non-empty YAML list")
        raise SystemExit(1)
    return data


def discover_from_tree() -> dict[str, list[Path]]:
    pages = sorted((REFERENCE / "src/app").rglob("page.tsx"))
    procedures = sorted((REFERENCE / "src/trpc/routers").rglob("*.procedure.ts"))
    procedures += [p for p in EXTRA_ROUTER_FILES if p.exists()]
    jest = sorted(
        list((REFERENCE / "src").rglob("*.test.ts"))
        + list((REFERENCE / "src").rglob("*.test.tsx"))
    )
    e2e = sorted((REFERENCE / "e2e").glob("*.spec.ts"))

    return {"pages": pages, "procedures": procedures, "jest": jest, "e2e": e2e}


def relative(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def read_manifest() -> dict[str, list[str]] | None:
    if not MANIFEST.exists():
        return None

    discovered: dict[str, list[str]] = {kind: [] for kind in KINDS}
    for number, line in enumerate(MANIFEST.read_text().splitlines(), start=1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        kind, _, path = line.partition(" ")
        if kind not in discovered or not path:
            fail(f"{MANIFEST.relative_to(ROOT)}:{number}: expected '<kind> <path>'")
            raise SystemExit(1)
        discovered[kind].append(path)
    return discovered


def write_manifest(discovered: dict[str, list[Path]]) -> None:
    lines = [
        "# Reference file inventory for the parity matrix.",
        "# Generated by: python scripts/check_parity_matrix.py --write-reference-manifest",
        "# The spliit/ tree itself is not committed; CI validates against this list.",
        "# Format: <kind> <repo-relative path>",
    ]
    for kind in KINDS:
        for path in discovered[kind]:
            lines.append(f"{kind} {relative(path)}")
    MANIFEST.write_text("\n".join(lines) + "\n")


def discover() -> dict[str, list[str]]:
    if REFERENCE.exists():
        tree = discover_from_tree()
        discovered = {kind: [relative(path) for path in tree[kind]] for kind in KINDS}
        manifest = read_manifest()
        if manifest is not None and manifest != discovered:
            fail(
                f"{MANIFEST.relative_to(ROOT)} is stale; regenerate it with "
                "`python scripts/check_parity_matrix.py --write-reference-manifest`"
            )
            raise SystemExit(1)
        return discovered

    manifest = read_manifest()
    if manifest is None:
        fail(
            f"missing reference source: {REFERENCE.relative_to(ROOT)} "
            f"(or inventory: {MANIFEST.relative_to(ROOT)})"
        )
        raise SystemExit(1)

    print(
        f"note: {REFERENCE.relative_to(ROOT)}/ is absent; "
        f"checking coverage against {MANIFEST.relative_to(ROOT)}",
        file=sys.stderr,
    )
    return manifest


def validate(rows: list[dict], discovered: dict[str, list[str]]) -> list[str]:
    errors: list[str] = []
    ids: Counter[str] = Counter()

    for index, row in enumerate(rows):
        label = row.get("id") or f"row[{index}]"

        if not isinstance(row, dict):
            errors.append(f"{label}: row is not a mapping")
            continue

        missing = [key for key in REQUIRED_FIELDS if key not in row]
        if missing:
            errors.append(f"{label}: missing fields {', '.join(missing)}")
            continue

        for key in REQUIRED_FIELDS:
            value = row[key]
            if key == "tests":
                continue
            if not isinstance(value, str) or value.strip().lower() in TBD_MARKERS:
                errors.append(f"{label}: field '{key}' is empty or TBD")

        ids[row["id"]] += 1

        if row["category"] not in VALID_CATEGORIES:
            errors.append(f"{label}: invalid category '{row['category']}'")
        if row["offline"] not in VALID_OFFLINE:
            errors.append(f"{label}: invalid offline '{row['offline']}'")
        if not str(row["stage"]).strip():
            errors.append(f"{label}: empty stage")

        tests = row["tests"]
        if not isinstance(tests, list) or not tests:
            errors.append(f"{label}: 'tests' must be a non-empty list")
        else:
            for test in tests:
                if not isinstance(test, str) or not test.strip() or test.strip().lower() in TBD_MARKERS:
                    errors.append(f"{label}: empty/TBD test entry")

    for identifier, count in ids.items():
        if count > 1:
            errors.append(f"duplicate feature id '{identifier}' ({count} rows)")

    references = [str(row.get("reference", "")) for row in rows]
    for kind, paths in discovered.items():
        for needle in paths:
            if not any(needle in reference for reference in references):
                errors.append(f"unmapped {KIND_LABELS[kind]}: {needle}")

    return errors


def write_report(rows: list[dict], discovered: dict[str, list[str]]) -> None:
    counts = Counter(row["category"] for row in rows)
    offline = Counter(row["offline"] for row in rows)
    by_stage: dict[str, list[dict]] = defaultdict(list)
    for row in rows:
        by_stage[str(row["stage"])].append(row)

    def stage_key(value: str):
        head = value.rstrip("ABCD")
        suffix = value[len(head):]
        try:
            return (float(head), suffix)
        except ValueError:
            return (999.0, value)

    lines = [
        "# Parity report",
        "",
        "Generated from `docs/parity-matrix.yml` by",
        "`scripts/check_parity_matrix.py`. Do not edit by hand.",
        "",
        "## Summary",
        "",
        f"- Features: **{len(rows)}** ({counts['standard']} standard, {counts['custom']} custom)",
        f"- Offline classes: {', '.join(f'{key}={value}' for key, value in sorted(offline.items()))}",
        f"- Reference pages discovered: {len(discovered['pages'])}",
        f"- Procedure files discovered: {len(discovered['procedures'])}",
        f"- Jest suites discovered: {len(discovered['jest'])}",
        f"- Playwright specs discovered: {len(discovered['e2e'])}",
        "",
    ]

    for stage in sorted(by_stage, key=stage_key):
        stage_rows = by_stage[stage]
        lines += [
            f"## Stage {stage} ({len(stage_rows)} features)",
            "",
            "| ID | Class | Reference | Target API | UI | Offline | Tests |",
            "|---|---|---|---|---|---|---|",
        ]
        for row in sorted(stage_rows, key=lambda item: item["id"]):
            tests = "<br>".join(f"`{test}`" for test in row["tests"])
            reference = f"`{row['reference']}`"
            lines.append(
                f"| {row['id']} | {row['category']} | {reference} | `{row['api']}` | "
                f"`{row['ui']}` | {row['offline']} | {tests} |"
            )
        lines.append("")

    REPORT.write_text("\n".join(lines).rstrip() + "\n")


def main() -> int:
    rows = load_matrix()

    if "--write-reference-manifest" in sys.argv[1:]:
        if not REFERENCE.exists():
            fail(f"cannot write manifest without reference source: {REFERENCE.relative_to(ROOT)}")
            return 1
        write_manifest(discover_from_tree())
        print(f"wrote {MANIFEST.relative_to(ROOT)}")

    discovered = discover()
    errors = validate(rows, discovered)

    if errors:
        for error in errors:
            fail(error)
        print(f"\n{len(errors)} parity-matrix error(s).", file=sys.stderr)
        return 1

    write_report(rows, discovered)
    print(
        "OK: {rows} features; {pages} pages, {procedures} procedure files, "
        "{jest} Jest suites, {e2e} Playwright specs all mapped.".format(
            rows=len(rows),
            pages=len(discovered["pages"]),
            procedures=len(discovered["procedures"]),
            jest=len(discovered["jest"]),
            e2e=len(discovered["e2e"]),
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
